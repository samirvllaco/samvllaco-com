// Renders the page in Cloudflare Browser Rendering: two desktop screenshots, one mobile, style metrics,
// an axe-core accessibility run and the mobile touch-target check. Screenshots are never stored.
import puppeteer from "@cloudflare/puppeteer";
import { METRICS_JS, TARGETS_JS } from "./_page.js"; // generated by slopscore/build.mjs from metrics.js
import { SLOP, BUZZWORDS } from "../config.js";
import { checkUrl } from "./url.js";

export class ScanError extends Error { constructor(code) { super(code); this.code = code; } }

let axeCache = "";
async function axeSource(env) {
  if (axeCache) return axeCache;
  const key = `axe:${SLOP.axeVersion}`;
  axeCache = (await env.CACHE.get(key)) || "";
  if (!axeCache) {
    const r = await fetch(`https://cdn.jsdelivr.net/npm/axe-core@${SLOP.axeVersion}/axe.min.js`);
    if (!r.ok) throw new Error("axe fetch");
    axeCache = await r.text();
    await env.CACHE.put(key, axeCache, { expirationTtl: 60 * 60 * 24 * 30 });
  }
  return axeCache;
}

const AXE_RUN = `axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"] }, resultTypes: ["violations"] })
  .then((r) => r.violations.map((v) => ({ id: v.id, impact: v.impact, help: v.help, nodes: v.nodes.length })))`;

async function steps(browser, env, url) {
  const page = await browser.newPage();
  await page.setBypassCSP(true);
  await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 });
  let resp;
  try { resp = await page.goto(url, { waitUntil: "domcontentloaded", timeout: SLOP.gotoMs }); } catch (e) { throw new ScanError(/timeout/i.test(e.message) ? "timeout" : "load"); }
  if (!resp) throw new ScanError("load");
  if (resp.status() >= 400) throw new ScanError(resp.status() === 403 || resp.status() === 429 ? "bot_blocked" : "load");
  await page.waitForNetworkIdle({ idleTime: 500, timeout: SLOP.idleMs }).catch(() => {});
  if (!checkUrl(page.url()).ok) throw new ScanError("blocked"); // redirected somewhere private
  // Scroll once so lazy images and scroll reveals render, then back to the top.
  await page.evaluate("(async () => { const h = Math.min(document.documentElement.scrollHeight, 4000); for (let y = 0; y < h; y += 700) { scrollTo(0, y); await new Promise((r) => setTimeout(r, 120)); } scrollTo(0, 0); await new Promise((r) => setTimeout(r, 200)); })()");
  const desk = await page.screenshot({ type: "jpeg", quality: 70, encoding: "base64" });
  const h = await page.evaluate("Math.max(900, Math.min(document.documentElement.scrollHeight, 3000))");
  const full = await page.screenshot({ type: "jpeg", quality: 60, encoding: "base64", clip: { x: 0, y: 0, width: 1440, height: h }, captureBeyondViewport: true }).catch(() => null);
  const metrics = await page.evaluate(`(${METRICS_JS})(${JSON.stringify(BUZZWORDS)})`);
  let axe = null;
  try { await page.addScriptTag({ content: await axeSource(env) }); axe = await page.evaluate(AXE_RUN); } catch { axe = null; }
  await page.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  await page.reload({ waitUntil: "domcontentloaded", timeout: 15000 }).catch(() => {});
  await page.waitForNetworkIdle({ idleTime: 500, timeout: 3000 }).catch(() => {});
  const mob = await page.screenshot({ type: "jpeg", quality: 70, encoding: "base64" });
  const targets = await page.evaluate(`(${TARGETS_JS})()`);
  return { shots: [desk, full, mob], metrics: { ...metrics, ...targets }, axe: axe || [], axeOk: axe !== null };
}

// Pages Functions cannot bind Browser Rendering, so the site reaches it through the samvllaco-scanner Worker
// (scanner/, service binding SCANNER). Inside that Worker, BROWSER is bound and the page renders here directly.
export async function render(env, url) {
  if (!env.BROWSER && env.SCANNER) {
    const r = await env.SCANNER.fetch("https://scanner/render", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ url }) });
    const j = await r.json().catch(() => ({ error: "load" }));
    if (j.error) throw new ScanError(j.error);
    return j;
  }
  let browser;
  try { browser = await puppeteer.launch(env.BROWSER); } catch (e) { throw new ScanError(/429|limit/i.test(e.message) ? "busy" : "load"); }
  let timer;
  try {
    return await Promise.race([steps(browser, env, url), new Promise((_, no) => { timer = setTimeout(() => no(new ScanError("timeout")), SLOP.budgetMs); })]);
  } finally {
    clearTimeout(timer);
    await browser.close().catch(() => {});
  }
}
