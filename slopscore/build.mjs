// Bundles the Slop Score API into functions/_slop/api.js (committed), so Cloudflare Pages deploys it with the site.
// Run after changing anything in slopscore/: node slopscore/build.mjs
// - The two in-page scripts become plain strings, so no bundler can rename or wrap them.
// - @cloudflare/puppeteer imports node:fs and node:path but never uses them here; they are stubbed, so the
//   Functions need no nodejs_compat flag and can never block a site deploy.
import { build } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";
import { collectMetrics, mobileTargets } from "./src/metrics.js";

const here = new URL(".", import.meta.url).pathname;
writeFileSync(`${here}src/_page.js`, `// Generated by slopscore/build.mjs from metrics.js. Do not edit.\nexport const METRICS_JS = ${JSON.stringify(collectMetrics.toString())};\nexport const TARGETS_JS = ${JSON.stringify(mobileTargets.toString())};\n`);
mkdirSync(`${here}../functions/_slop`, { recursive: true });
const stub = { name: "node-stub", setup(b) { b.onResolve({ filter: /^node:(fs|path)$/ }, (a) => ({ path: a.path, namespace: "stub" })); b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "export default {}; export const promises = {};", loader: "js" })); } };
await build({
  entryPoints: [`${here}src/api.js`],
  outfile: `${here}../functions/_slop/api.js`,
  bundle: true, format: "esm", platform: "neutral", target: "es2022", minify: true, legalComments: "none",
  mainFields: ["module", "main"], conditions: ["workerd", "worker", "browser"], plugins: [stub],
  banner: { js: "// Generated by slopscore/build.mjs. Do not edit; change slopscore/src and rebuild." },
});
console.log("built functions/_slop/api.js");
